// Initialize i18n system
function initI18n() {
  const savedLanguage = localStorage.getItem('selectedLanguage') || 'en';
  setLanguage(savedLanguage);
}

// Set current language and translate page
function setLanguage(lang) {
  if (!translations[lang]) return;
  
  localStorage.setItem('selectedLanguage', lang);
  document.documentElement.lang = lang;
  
  // Update all elements with data-i18n attribute
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const key = element.getAttribute('data-i18n');
    if (translations[lang][key]) {
      if (element.tagName === 'IMG') {
        element.alt = translations[lang][key];
      } else if (element.tagName === 'A') {
        // For links, only update text content, not the href
        element.textContent = translations[lang][key];
      } else {
        // For other elements, check if they have child elements with data-i18n
        // If yes, don't update (those children will be updated separately)
        // If no, update the text content
        const hasTranslatableChildren = element.querySelector('[data-i18n]');
        if (!hasTranslatableChildren) {
          element.textContent = translations[lang][key];
        }
      }
    }
  });
  
  // Update page title
  if (translations[lang]['title']) {
    document.title = translations[lang]['title'];
  }
  
  // Update active button
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.remove('active');
    if (btn.getAttribute('data-lang') === lang) {
      btn.classList.add('active');
    }
  });
}

// Initialize on page load
document.addEventListener('DOMContentLoaded', initI18n);
